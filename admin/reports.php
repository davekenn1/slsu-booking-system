$total_result = mysqli_query($conn, $total_sql);
$total_count = mysqli_fetch_assoc($total_result)['total'];

// Count approved
$approved_sql = "SELECT COUNT(*) as total FROM bookings WHERE booking_date BETWEEN '$start_date' AND '$end_date' AND status = 'approved'";
$approved_result = mysqli_query($conn, $approved_sql);
$approved_count = mysqli_fetch_assoc($approved_result)['total'];

// Count pending
$pending_sql = "SELECT COUNT(*) as total FROM bookings WHERE booking_date BETWEEN '$start_date' AND '$end_date' AND status = 'pending'";
