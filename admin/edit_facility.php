session_start();
require_once '../includes/config.php';

// Use session-based connection
$conn = getSessionConnection();

// Check if user is logged in and is admin
if(!isset($_SESSION['user_id']) || $_SESSION['role'] != 'admin') {
    header("Location: ../login.php");
    exit();
}

$facility_id = isset($_GET['id']) ? $_GET['id'] : 0;
$error = '';
$success = '';

// Get facility details
$sql = "SELECT * FROM facilities WHERE id = $facility_id";
$result = mysqli_query($conn, $sql);
$facility = mysqli_fetch_assoc($result);

if(!$facility) {
    header("Location: manage_facilities.php");
    exit();
}

// Handle form submission
if($_SERVER['REQUEST_METHOD'] == 'POST') {
    $name = mysqli_real_escape_string($conn, $_POST['name']);
    $description = mysqli_real_escape_string($conn, $_POST['description']);
    $capacity = mysqli_real_escape_string($conn, $_POST['capacity']);
    $open_time = mysqli_real_escape_string($conn, $_POST['open_time']);
    $close_time = mysqli_real_escape_string($conn, $_POST['close_time']);   
    $status = mysqli_real_escape_string($conn, $_POST['status']);

    // Handle image upload
    $image = $facility['image']; // Keep existing image by default
    if(isset($_FILES['image']) && $_FILES['image']['error'] == 0) {
        $allowed = ['jpg', 'jpeg', 'png', 'gif'];
        $filename = $_FILES['image']['name'];
        $ext = strtolower(pathinfo($filename, PATHINFO_EXTENSION));
        
        if(in_array($ext, $allowed)) {
            $new_filename = time() . '_' . preg_replace('/[^a-zA-Z0-9]/', '_', $filename);
            $upload_path = '../uploads/facilities/' . $new_filename;
            
            if(move_uploaded_file($_FILES['image']['tmp_name'], $upload_path)) {
                $image = $new_filename;
            }
        }
    }
    
    $price = mysqli_real_escape_string($conn, $_POST['price']);
    $update_sql = "UPDATE facilities SET 
               name = '$name',
               description = '$description',
               capacity = '$capacity',
               price = '$price',
               image = '$image',
               open_time = '$open_time',
               close_time = '$close_time',
               status = '$status'
               WHERE id = $facility_id";

                if(mysqli_query($conn, $update_sql)) {
                // Generate new hash from updated data
                $hash_data = [
                    $facility_id,
                    $name,
                    $description,
                    $capacity,
                    $price,
                    $open_time,
                    $close_time,
                    $status
                ];
                $row_hash = generateRowHash($hash_data);
                
                // Update the hash in facilities table
                $update_hash = "UPDATE facilities SET row_hash = '$row_hash' WHERE id = $facility_id";
                mysqli_query($conn, $update_hash);
                
                // Also update hash_table
                $update_hash_log = "UPDATE hash_table SET row_hash = '$row_hash', updated_at = NOW() 
                                    WHERE table_name = 'facilities' AND record_id = $facility_id";
                mysqli_query($conn, $update_hash_log);
                
                $success = "✅ Facility updated successfully!";
            } else {
                $error = "❌ Error updating facility: " . mysqli_error($conn);
            }
}
